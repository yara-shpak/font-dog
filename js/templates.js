  /** Повертає масив [x, y] для шаблону 5×7(+2), де y рахується від базової лінії вгору.
      tall: брати повновисоку версію, якщо над великими є щонайменше 2 рядки. */
  function cellsOf(ch, opts) {
    let src = (opts && opts.tall && TALL[ch]) || T[ch];
    let guard = 0;
    while (src !== undefined && Array.from(src).length === 1 && guard++ < 4) src = T[src];
    if (src === undefined) return null;
    const out = [];
    if (src.includes('|')) {
      const parts = src.split('|');
      const above = parts[0].split('/');
      above.forEach((row, r) => {
        const y = 7 + (above.length - 1 - r);
        for (let x = 0; x < row.length; x++) if (row[x] === '#') out.push([x, y]);
      });
      src = parts[1];
    }
    src.split('/').forEach((row, r) => {
      const y = 6 - r; // 0 — нижній рядок тіла; -1, -2 — виносні
      for (let x = 0; x < row.length; x++) if (row[x] === '#') out.push([x, y]);
    });
    return out;
  }

  FL.templates = { raw: T, TALL, cellsOf, has: (ch) => cellsOf(ch) !== null };
